    /*
     * Llena la lista con los tipos que estan registrados en la base. Asi, si
     * despues se agrega un tipo nuevo a la tabla, aparece solo en la ventana.
     */
    private void cargarTipos() {

        cbTipo.removeAllItems();

        try {

            for (String tipo : gestorIncidencias.obtenerTipos()) {
                cbTipo.addItem(tipo);
            }

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(this,
                    "No se pudieron cargar los tipos de incidencia.\n" + ex.getLocalizedMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE);
        }
    }

