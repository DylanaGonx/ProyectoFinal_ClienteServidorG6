    //Guarda la incidencia
    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

        if (txtDescripcion.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe describir la incidencia.");
            return;
        }

        if (cbTipo.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Debe escoger el tipo de incidencia.");
            return;
        }

        try {

            //El vehiculo puede venir nulo, el gestor se encarga de avisarlo
            String placa = null;

            if (paquete.getVehiculo() != null) {
                placa = paquete.getVehiculo().getPlaca();
            }

            gestorIncidencias.registrarIncidencia(
                    paquete.getId(),
                    placa,
                    cbTipo.getSelectedItem().toString(),
                    txtDescripcion.getText());

            JOptionPane.showMessageDialog(this, "Incidencia registrada correctamente");

            //Refresca el monitor para que la alerta aparezca de una vez
            principal.actualizarTabla();

            dispose();

        } catch (DatosInvalidosException ex) {

            JOptionPane.showMessageDialog(this, ex.getMessage());

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(this,
                    "No se pudo guardar la incidencia.\n" + ex.getLocalizedMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

