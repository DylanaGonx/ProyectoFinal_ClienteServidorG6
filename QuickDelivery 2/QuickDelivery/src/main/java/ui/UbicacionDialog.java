    //Manda el reporte de ubicacion
    private void btnEnviarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnviarActionPerformed

        if (txtLatitud.getText().trim().isEmpty() || txtLongitud.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe digitar la latitud y la longitud.");
            return;
        }

        try {

            //Las coordenadas se convierten aqui, dentro del try, por si vienen con letras
            double latitud = Double.parseDouble(txtLatitud.getText().trim());
            double longitud = Double.parseDouble(txtLongitud.getText().trim());

            //Rango valido de coordenadas
            if (latitud < -90 || latitud > 90) {
                JOptionPane.showMessageDialog(this, "La latitud tiene que estar entre -90 y 90.");
                return;
            }

            if (longitud < -180 || longitud > 180) {
                JOptionPane.showMessageDialog(this, "La longitud tiene que estar entre -180 y 180.");
                return;
            }

            String placa = obtenerPlacaSeleccionada();
            String estado = cbEstado.getSelectedItem().toString();

            gestorUbicaciones.registrarUbicacion(placa, latitud, longitud, estado);

            //El vehiculo tambien queda con ese estado en la flota
            gestorVehiculos.cambiarEstado(placa, estado);

            reportesEnviados++;

            JOptionPane.showMessageDialog(this,
                    "Ubicación reportada.\n"
                    + "Vehículo " + placa + " en " + latitud + ", " + longitud + "\n"
                    + "Reportes enviados en esta sesión: " + reportesEnviados);

            //La ventana se queda abierta para seguir reportando la ruta
            txtLatitud.setText("");
            txtLongitud.setText("");
            txtLatitud.requestFocus();

            principal.actualizarTabla();

        } catch (NumberFormatException ex) {

            JOptionPane.showMessageDialog(this,
                    "La latitud y la longitud tienen que ser valores numericos.\n"
                    + "Se usa el punto como separador decimal, por ejemplo 9.9333300");

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(this,
                    "No se pudo guardar la ubicación.\n" + ex.getLocalizedMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEnviarActionPerformed

