    /*
     * Llena el combo unicamente con los vehiculos que tiene asignados este
     * conductor. Asi no puede reportar por un vehiculo que no maneja.
     */
    private void cargarVehiculos() {

        cbVehiculo.removeAllItems();

        try {

            for (Vehiculo vehiculo : gestorVehiculos.obtenerVehiculosDeConductor(conductor.getUsuario())) {
                cbVehiculo.addItem(vehiculo.getPlaca() + " (" + vehiculo.getTipo() + ")");
            }

            if (cbVehiculo.getItemCount() == 0) {

                JOptionPane.showMessageDialog(this,
                        "El usuario " + conductor.getUsuario() + " no tiene vehiculos asignados.\n"
                        + "El administrador debe asignarle uno para poder reportar la ubicacion.",
                        "Sin vehiculo",
                        JOptionPane.WARNING_MESSAGE);

                btnEnviar.setEnabled(false);
            }

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(this,
                    "No se pudo cargar la flota del conductor.\n" + ex.getLocalizedMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE);

            btnEnviar.setEnabled(false);
        }
    }

    /*
     * Del texto del combo se saca solo la placa, que es lo que va antes del
     * parentesis. Ejemplo: de "CRC-001 (Automovil)" saca "CRC-001".
     */
    private String obtenerPlacaSeleccionada() {
        return cbVehiculo.getSelectedItem().toString().split(" ")[0];
    }

