    //Arma las columnas de la tabla
    private void cargarTabla() {

        String columnas[] = {"ID", "Usuario", "Rol"};

        //La tabla es solo de consulta, los cambios van por los botones
        modeloTabla = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };

        tblUsuarios.setModel(modeloTabla);
        tblUsuarios.setRowHeight(22);
        tblUsuarios.getTableHeader().setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 13));
    }

    //Trae los usuarios de la base y los pone en la tabla
    private void actualizarTabla() {

        try {

            modeloTabla.setRowCount(0);

            for (Usuario usuario : gestorUsuarios.obtenerUsuarios()) {
                modeloTabla.addRow(new Object[]{
                    usuario.getId(),
                    usuario.getUsuario(),
                    usuario.getrol()
                });
            }

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(this,
                    "No se pudieron consultar los usuarios.\n" + ex.getLocalizedMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limpiar() {
        txtUsuario.setText("");
        txtContrasenia.setText("");
        cbRol.setSelectedIndex(0);
        txtUsuario.setEnabled(true);
        tblUsuarios.clearSelection();
        txtUsuario.requestFocus();
    }

    /*
     * Segun el rol escogido se crea la subclase que corresponde. Todas se
     * manejan como Usuario, que es el polimorfismo del modelo.
     */
    private Usuario crearUsuario(String nombre, String clave, String rol) {

        switch (rol) {
            case "Administrador":
                return new Administrador(nombre, clave);
            case "Despachador":
                return new Despachador(nombre, clave);
            default:
                return new Conductor(nombre, clave);
        }
    }

