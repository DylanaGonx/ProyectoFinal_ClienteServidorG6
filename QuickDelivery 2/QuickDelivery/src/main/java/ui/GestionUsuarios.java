    //Al hacer clic en una fila se cargan los datos en los campos
    private void tblUsuariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsuariosMouseClicked
        int fila = tblUsuarios.getSelectedRow();

        if (fila == -1) {
            return;
        }

        txtUsuario.setText(tblUsuarios.getValueAt(fila, 1).toString());
        cbRol.setSelectedItem(tblUsuarios.getValueAt(fila, 2).toString());
        txtContrasenia.setText("");

        //El nombre de usuario no se cambia, es la llave con la que se busca
        txtUsuario.setEnabled(false);
    }//GEN-LAST:event_tblUsuariosMouseClicked

    //Registra un usuario nuevo
    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed

        String nombre = txtUsuario.getText().trim();
        String clave = new String(txtContrasenia.getPassword()).trim();

        if (nombre.isEmpty() || clave.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe digitar el usuario y la contraseña.");
            return;
        }

        try {

            gestorUsuarios.agregarUsuario(crearUsuario(nombre, clave, cbRol.getSelectedItem().toString()));

            JOptionPane.showMessageDialog(this, "Usuario registrado correctamente");

            actualizarTabla();
            limpiar();

        } catch (UsuarioDuplicadoException ex) {

            JOptionPane.showMessageDialog(this, ex.getMessage());

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(this,
                    "No se pudo registrar el usuario.\n" + ex.getLocalizedMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    //Cambia la contraseña del usuario seleccionado
    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed

        if (tblUsuarios.getSelectedRow() == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un usuario de la tabla.");
            return;
        }

        String nombre = txtUsuario.getText().trim();
        String clave = new String(txtContrasenia.getPassword()).trim();

        if (clave.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite la contraseña nueva.");
            return;
        }

        try {

            gestorUsuarios.modificarUsuario(crearUsuario(nombre, clave, cbRol.getSelectedItem().toString()));

            JOptionPane.showMessageDialog(this, "Contraseña actualizada");

            actualizarTabla();
            limpiar();

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(this,
                    "No se pudo modificar el usuario.\n" + ex.getLocalizedMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnModificarActionPerformed

    //Da de baja al usuario seleccionado
    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

        if (tblUsuarios.getSelectedRow() == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un usuario de la tabla.");
            return;
        }

        String nombre = txtUsuario.getText().trim();

        //No tiene sentido que el administrador se de de baja a si mismo
        if (nombre.equals(usuarioSesion.getUsuario())) {
            JOptionPane.showMessageDialog(this,
                    "No puede dar de baja el usuario con el que tiene la sesión abierta.",
                    "Operación no permitida",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        int opcion = JOptionPane.showConfirmDialog(this,
                "¿Desea dar de baja al usuario " + nombre + "?",
                "Confirmar",
                JOptionPane.YES_NO_OPTION);

        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }

        try {

            gestorUsuarios.eliminarUsuario(nombre);

            JOptionPane.showMessageDialog(this, "Usuario dado de baja");

            actualizarTabla();
            limpiar();

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(this,
                    "No se pudo dar de baja el usuario.\n" + ex.getLocalizedMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

